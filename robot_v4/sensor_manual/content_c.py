TAU, HOLD, THR = 0.15, 0.30, 0.5      # firmware: low-pass ~0.15 s, hold 0.3 s, +-0.5 g


def flip_time(theta_deg):
    """Seconds from a step tilt (from upright) until the firmware declares inverted; None = never."""
    az = math.cos(math.radians(theta_deg))
    if az >= -THR:
        return None
    return TAU * math.log((1 - az) / (-THR - az)) + HOLD


