def section12(d):
    d.h1('Blind Spot Test (ทดสอบตรวจกลับหัวทุกมุม)')
    d.note('ต้นแบบให้วางวัตถุรอบรถที่ 0–315° ระยะ 10–50 cm · V4 ไม่มี sensor วัดระยะ จึงใช้ตารางเดียวกันกับ<b>มุมเอียงของตัวรถ</b> (0–315°) และ<b>เวลาค้าง</b> (0.2–1.5 s) แทนระยะ '
           'เพื่อหา "มุมบอด" ของการตรวจกลับหัว ' + tag('REC'), 'adapt')
    d.figure(figs4.tilt_polar(), 'แผนที่สถานะตามมุมเอียง: az = cos θ เทียบเกณฑ์ ±0.5 g ' + tag('FW'))
    d.p('วิธีทำ: ถอดโรเตอร์ เริ่มจากรถตั้งปกติ (inv=0) จับรถหมุนรอบแกน Roll (ตะแคง) ไปที่มุมที่กำหนดเร็วๆ ค้างตามเวลา แล้วอ่าน inv ใน Serial · ทำซ้ำรอบแกน Pitch (หัวทิ่ม) · '
        'ค่าคาดหมายคำนวณจากตัวกรองในเฟิร์มแวร์ (τ ≈ 0.15 s, ค้าง 0.3 s) ' + tag('FW') + ' ตัวเลขในวงเล็บคือเวลาที่คาดว่าจะสลับ')
    d.p('ผลที่ยอมรับได้: ทุกช่องตรงกับค่าคาด · มุม 90° และ 270° ต้องคงสถานะเดิม (ไม่สลับไปมาเมื่อรถตะแคงพิงผนัง) · ถ้าช่อง 0.2/0.4 s สลับ = ตัวกรองไม่ทำงาน ห้ามใช้แข่ง')
    holds = [0.2, 0.4, 0.8, 1.5]
    rows = []
    for a in range(0, 360, 45):
        t = flip_time(a)
        az = math.cos(math.radians(a))
        if t is None:
            zone = 'ปกติ' if az > THR else 'คงสถานะ'
            exp = ['0'] * 4
        else:
            zone = 'กลับหัว (%.2f s)' % t
            exp = ['1' if h > t else '0' for h in holds]
        rows.append(['%d°' % a, '%+.2f' % (0.0 if abs(az) < 1e-9 else az), zone] + ['คาด %s · Roll %s Pitch %s' % (e, B, B) for e in exp])
    d.table(['มุม', 'az', 'โซน', 'ค้าง 0.2 s', 'ค้าง 0.4 s', 'ค้าง 0.8 s', 'ค้าง 1.5 s'], rows,
            'ตารางผล Blind Spot Test (กรอกค่า inv ที่อ่านได้: 0 = ปกติ, 1 = กลับหัว)', widths=['7%', '8%', '15%', '17.5%', '17.5%', '17.5%', '17.5%'], cls='keep')


